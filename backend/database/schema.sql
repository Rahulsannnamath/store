-- MySQL 8.0.16+ - select an EMPTY database before running. No data is removed.
CREATE TABLE users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(60) NOT NULL,
 email VARCHAR(254) NOT NULL,
 password VARCHAR(255) NOT NULL,
 address VARCHAR(400) NOT NULL,
 role ENUM('user','admin','store_owner') NOT NULL DEFAULT 'user',
 token_version INT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT uq_users_email UNIQUE (email),
 CONSTRAINT chk_users_name CHECK (CHAR_LENGTH(TRIM(name)) BETWEEN 20 AND 60),
 CONSTRAINT chk_users_address CHECK (CHAR_LENGTH(TRIM(address)) BETWEEN 1 AND 400)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE storedata (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(60) NOT NULL,
 email VARCHAR(254) NOT NULL,
 address VARCHAR(400) NOT NULL,
 owner_id INT UNSIGNED NOT NULL,
 image_url VARCHAR(2048) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_store_name (name),
 INDEX idx_store_owner (owner_id),
 CONSTRAINT fk_store_owner FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT chk_store_name CHECK (CHAR_LENGTH(TRIM(name)) BETWEEN 1 AND 60),
 CONSTRAINT chk_store_address CHECK (CHAR_LENGTH(TRIM(address)) BETWEEN 1 AND 400)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE ratings (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id INT UNSIGNED NOT NULL,
 store_id INT UNSIGNED NOT NULL,
 rating DECIMAL(3,1) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT uq_rating_user_store UNIQUE (user_id, store_id),
 CONSTRAINT fk_rating_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_rating_store FOREIGN KEY (store_id) REFERENCES storedata(id) ON DELETE RESTRICT,
 CONSTRAINT chk_rating_range CHECK (rating BETWEEN 1 AND 5 AND rating = FLOOR(rating))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

